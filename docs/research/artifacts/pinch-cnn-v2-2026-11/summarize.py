"""Summarise every results/*.json into RESULTS.md: each model at its own chosen threshold, and at matched false-activation
rates (the highest-recall threshold whose everyday rate is at most 5/h and 10/h).

The matched rows pick the threshold on the test set, so they compare models with one another; they are not a deployable
result. The "chosen" row is the honest one.
"""
import json

import numpy as np
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUDGETS = (5.0, 10.0)


def row(name, th, r):
    ev = r["everyday"]
    rate = ev["fa"] / max(ev["neg_h"], 1e-9)
    c = lambda g: f"{r[g]['caught']}/{r[g]['gestures']}"
    return f"| {name} | {th} | {c('live')} | {c('moving')} | {c('resting')} | {ev['fa']} ({rate:.1f}/h) | {r['still']['fa']} |"


def main():
    runs = [json.loads(p.read_text()) for p in sorted((HERE / "results").glob("*.json"))]
    head = ["| Model | Activation | Live (20) | Moving (102) | Resting (57) | Everyday FA (0.61 h) | Still FA |",
            "|---|---|---|---|---|---|---|"]
    out = ["# Pinch-start v2: results so far", "",
           "Generated by `summarize.py` from `results/*.json`. Benchmark and split: [README.md](README.md).", "",
           "## At each model's own threshold (chosen without the test set)", "", *head]
    for run in runs:
        th = run["chosen"]
        if th is None:
            out.append(f"| {run['name']} | not chosen (screening run) | | | | | |")
            continue
        r ={g: v[str(float(th))] if str(float(th)) in v else v[str(th)] for g, v in run["results"].items()}
        out.append(row(run["name"], f"{th:g}", r))
    for budget in BUDGETS:
        out += ["", f"## At matched false activations: everyday at most {budget:g}/h (threshold picked on the test set)", "", *head]
        for run in runs:
            best = None
            for th in run["results"]["live"]:
                r = {g: v[th] for g, v in run["results"].items()}
                ev = r["everyday"]
                if ev["fa"] / max(ev["neg_h"], 1e-9) > budget:
                    continue
                key = (r["live"]["caught"] + r["moving"]["caught"] + r["resting"]["caught"], float(th))
                if best is None or key > best[0]:
                    best = (key, th, r)
            out.append(row(run["name"], f"{float(best[1]):g}", best[2]) if best else f"| {run['name']} | none within | | | | | |")
    # Seeds of one configuration (names that differ only by "-sNN"), averaged at each budget.
    import re
    configs: dict[str, list[dict]] = {}
    for run in runs:
        configs.setdefault(re.sub(r"-s\d+", "", run["name"]), []).append(run)
    for budget in BUDGETS:
        out += ["", f"## Mean over seeds, everyday at most {budget:g}/h (threshold picked on the test set, per seed)", "",
                "| Configuration | Seeds | Live (20) | Moving (102) | Resting (57) | Everyday rate |", "|---|---|---|---|---|---|"]
        for cfg, members in sorted(configs.items()):
            picks = []
            for run in members:
                best = None
                for th in run["results"]["live"]:
                    r = {g: v[th] for g, v in run["results"].items()}
                    rate = r["everyday"]["fa"] / max(r["everyday"]["neg_h"], 1e-9)
                    if rate > budget:
                        continue
                    key = (r["live"]["caught"] + r["moving"]["caught"] + r["resting"]["caught"], float(th))
                    if best is None or key > best[0]:
                        best = (key, r, rate)
                if best:
                    picks.append(best)
            if not picks:
                continue
            m = lambda g: np.mean([p[1][g]["caught"] for p in picks])
            sd = lambda g: np.std([p[1][g]["caught"] for p in picks])
            out.append(f"| {cfg} | {len(picks)} | {m('live'):.1f} ± {sd('live'):.1f} | {m('moving'):.1f} ± {sd('moving'):.1f} | "
                       f"{m('resting'):.1f} ± {sd('resting'):.1f} | {np.mean([p[2] for p in picks]):.1f}/h |")
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
